def _load_custom_phrases() -> dict:
    """Загружает пользовательские фразы."""
    phrases_file = _data_path("custom_phrases.json")
    if os.path.exists(phrases_file):
        with open(phrases_file, "r", encoding="utf-8") as f:
            return json.load(f)
    return {}


def _save_custom_phrases(phrases: dict):
    """Сохраняет пользовательские фразы."""
    data_dir = os.path.dirname(_data_path("custom_phrases.json"))
    os.makedirs(data_dir, exist_ok=True)
    with open(_data_path("custom_phrases.json"), "w", encoding="utf-8") as f:
        json.dump(phrases, ensure_ascii=False, indent=2)


def create_custom_category(category: str) -> bool:
    """Создаёт новую пользовательскую категорию."""
    custom = _load_custom_phrases()
    if category not in custom:
        custom[category] = []
        _save_custom_phrases(custom)
        return True
    return False


def add_custom_phrase(category: str, phrase: str) -> bool:
    """Добавляет фразу в пользовательскую категорию."""
    custom = _load_custom_phrases()
    if category not in custom:
        custom[category] = []
    if phrase not in custom[category]:
        custom[category].append(phrase)
        _save_custom_phrases(custom)
        return True
    return False


def delete_custom_phrase(category: str, phrase: str) -> bool:
    """Удаляет фразу из пользовательской категории."""
    custom = _load_custom_phrases()
    if category in custom and phrase in custom[category]:
        custom[category].remove(phrase)
        if not custom[category]:
            del custom[category]
        _save_custom_phrases(custom)
        return True
    return False


def get_all_categories() -> list:
    """Возвращает все категории (встроенные + пользовательские)."""
    custom = _load_custom_phrases()
    builtin = ["love", "nature", "pain", "hope", "dreams", "time"]
    return builtin + [c for c in custom.keys() if c not in builtin]


def get_phrases_by_category(category: str) -> list:
    """
    Получить список фраз по категории.

    Args:
        category: Название категории (love, nature, pain, hope, dreams, time).

    Returns:
        Список фраз указанной категории.
        Если категория не найдена, возвращает пустой список.
    """
    # Сначала проверяем пользовательские фразы
    custom = _load_custom_phrases()
    if category in custom:
        return custom[category]

    # Потом встроенные
    return PHRASES.get(category, [])


def search_phrases(keyword: str) -> list:
    """
    Поиск фраз по ключевому слову.

    Args:
        keyword: Ключевое слово для поиска.

    Returns:
        Список фраз, содержащих ключевое слово (без учёта регистра).
    """
    keyword_lower = keyword.lower().strip()
    if not keyword_lower:
        return []

    results = []
    for category, phrases in PHRASES.items():
        for phrase in phrases:
            if keyword_lower in phrase.lower():
                results.append({"phrase": phrase, "category": category})

    return results


def get_random_phrases(count: int = 1, category: str = None) -> list:
    """
    Получить случайные фразы.

    Args:
        count: Количество фраз для выбора (по умолчанию 1).
        category: Если указана, фразы выбираются из этой категории.
                  Если None, фразы выбираются из всех категорий.

    Returns:
        Список случайных фраз.
    """
    import random

    if category:
        phrases = get_phrases_by_category(category)
    else:
        phrases = []
        for category_phrases in PHRASES.values():
            phrases.extend(category_phrases)

    if not phrases:
        return []

    return random.sample(phrases, min(count, len(phrases)))
